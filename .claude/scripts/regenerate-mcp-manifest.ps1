<#
.SYNOPSIS
  Regenerate ~/.claude/mcp-manifest.json from ~/.claude.json.

.DESCRIPTION
  The manifest is the source-controlled, secret-redacted record of MCP servers.
  Run this after adding/removing/editing MCPs so git tracks the change.

  Secrets in env vars (TOKEN/KEY/SECRET/PASSWORD/PAT/AUTH) are replaced with
  "VAULT:<server>/<lowercased-env-key>" sentinels; bootstrap resolves them.
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$config   = Join-Path $env:USERPROFILE '.claude.json'
$manifest = Join-Path $env:USERPROFILE '.claude\mcp-manifest.json'

if (-not (Test-Path $config)) { throw "Missing: $config" }

$py = @"
import json, sys, datetime
src = r'$config'
dst = r'$manifest'
d = json.load(open(src, encoding='utf-8'))
mcp = d.get('mcpServers', {})
out = {
    '_comment': 'Source of truth for MCP server config. Auto-generated by regenerate-mcp-manifest.ps1. Secrets resolved via vault at bootstrap.',
    'generated_at': datetime.date.today().isoformat(),
    'mcp_count': len(mcp),
    'servers': {},
}
for name, cfg in sorted(mcp.items()):
    sanitized = {k: v for k, v in cfg.items() if k != 'env'}
    env = cfg.get('env', {}) or {}
    se = {}
    for ek, ev in env.items():
        if isinstance(ev, str) and any(s in ek.upper() for s in ('TOKEN','KEY','SECRET','PASSWORD','PAT','AUTH')):
            se[ek] = f'VAULT:{name}/{ek.lower()}'
        else:
            se[ek] = ev
    if se:
        sanitized['env'] = se
    out['servers'][name] = sanitized
with open(dst, 'w', encoding='utf-8') as f:
    json.dump(out, f, indent=2, ensure_ascii=False)
print(f'wrote {dst}')
print(f'servers: {len(mcp)}')
"@

$tmp = Join-Path $env:TEMP "regen-manifest-$(Get-Random).py"
Set-Content -Path $tmp -Value $py -Encoding UTF8
try {
    & python $tmp
    if ($LASTEXITCODE -ne 0) { throw "Manifest regeneration failed (exit $LASTEXITCODE)" }
} finally {
    Remove-Item $tmp -Force -ErrorAction SilentlyContinue
}
